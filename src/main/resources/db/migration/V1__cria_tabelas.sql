CREATE TABLE customers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel      VARCHAR(10)  NOT NULL CHECK (channel IN ('WEB', 'WHATSAPP')),
    external_id  VARCHAR(64)  NOT NULL,            -- WEB: UUID da sessão; WHATSAPP: wa_id
    phone        VARCHAR(20)  NOT NULL,
    name         VARCHAR(60),
    created_at   TIMESTAMPTZ  NOT NULL,
    last_seen_at TIMESTAMPTZ  NOT NULL,            -- renovado a cada mensagem; base da retenção do WhatsApp
    CONSTRAINT uk_customers_channel_external UNIQUE (channel, external_id)
);
CREATE INDEX idx_customers_channel_created ON customers (channel, created_at);
CREATE INDEX idx_customers_channel_last_seen ON customers (channel, last_seen_at);

CREATE TABLE conversations (
    customer_id       BIGINT      PRIMARY KEY REFERENCES customers (id) ON DELETE CASCADE,
    state             JSONB       NOT NULL,
    misunderstandings SMALLINT    NOT NULL DEFAULT 0 CHECK (misunderstandings >= 0),
    updated_at        TIMESTAMPTZ NOT NULL
);

-- Agendamentos criados pelo atendente: o agendamento-api não busca por telefone.
CREATE TABLE bookings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       BIGINT         NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    appointment_id    BIGINT         NOT NULL,     -- id no agendamento-api
    service_id        BIGINT         NOT NULL,     -- vem do rascunho; a API não devolve serviceId
    service_name      VARCHAR(100)   NOT NULL,
    professional_id   BIGINT         NOT NULL,
    professional_name VARCHAR(100)   NOT NULL,
    price             NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    start_at          TIMESTAMP      NOT NULL,     -- horário local do estabelecimento, como no agendamento-api
    end_at            TIMESTAMP      NOT NULL,
    status            VARCHAR(10)    NOT NULL CHECK (status IN ('SCHEDULED', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    created_at        TIMESTAMPTZ    NOT NULL,
    updated_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uk_bookings_appointment UNIQUE (appointment_id),
    CONSTRAINT ck_bookings_interval CHECK (start_at < end_at)
);
CREATE INDEX idx_bookings_customer_start ON bookings (customer_id, start_at);

-- Idempotência por cliente (wamid ou clientMessageId) e resposta guardada da web por 24 h.
CREATE TABLE processed_messages (
    customer_id  BIGINT       NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    message_id   VARCHAR(128) NOT NULL,
    reply        JSONB,
    processed_at TIMESTAMPTZ  NOT NULL,
    PRIMARY KEY (customer_id, message_id)
);
CREATE INDEX idx_processed_messages_processed_at ON processed_messages (processed_at);
